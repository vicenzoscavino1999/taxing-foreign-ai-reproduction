"""Table 6 (classification of the 1,728 claims) and Table 4 (ceilings at the witnesses) from the output of
`reproducir.py fam13-reproducir`.

FAM13 regenerates the claim-level confrontation table (T7_anexo) and its aggregate (T7) from the stored certified values
of the full run and checks that the regenerated bytes equal the accepted ones. This script only counts and summarizes
that regenerated table; it does not recompute any ceiling.

Usage: python -B -I tools/tables_from_fam13.py <fam13 output folder>
Writes <folder>/../table6.md and table4_stored.md next to the FAM13 folder; exit code 0 if FAM13 accepted its products
and every cell equals the printed article.
"""
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
F13 = Path(sys.argv[1]).resolve()
OUT = F13.parent
CATS = ("cambio_de_signo_certificado", "inconclusa_por_testigos_en_tolerancia", "robusta_infactible_certificada")
ARTICLE_T6 = [  # (label, availability, claims, sign change certified, inconclusive within tolerance, robustly infeasible)
    ("Country-instrument, j=df", "withholding available", 320, 320, 0, 0),
    ("Country-instrument, j=d", "domestic unchanged", 320, 320, 0, 0),
    ("Country-instrument, j=f", "withholding available", 320, 116, 188, 16),
    ("  Peru", "", 160, 104, 56, 0),
    ("  Colombia", "", 96, 12, 84, 0),
    ("  Mexico", "", 64, 0, 48, 16),
    ("Country, best menu", "full / none", 640, 640, 0, 0),
    ("Three countries", "full / none", 128, 128, 0, 0),
    ("Total", "", 1728, 1524, 188, 16),
]
ARTICLE_T4 = {("df", "G"): ("0.7917", "0.0005-0.0019"), ("df", "N"): ("0.5628", "0.0005-0.0022"),
              ("d", "G"): ("0.5475", "0.0004-0.0017"), ("d", "N"): ("0.4380", "0.0004-0.0017"),
              ("f", "G"): ("0.2737", "0.00003"), ("f", "N"): ("0.2737", "0.00003")}


def num(x):
    return None if x in ("", "null", None) else float(x)


def main():
    summary = json.loads((F13 / "resumen.json").read_text(encoding="utf-8"))
    comp = json.loads((F13 / "t7.comparacion.json").read_text(encoding="utf-8"))
    accepted = summary.get("cumple") is True and comp.get("cumple") is True and comp["estado"]["reproduccion"] == "aceptada"
    rows = list(csv.DictReader(open(F13 / "t7" / "ensamblajes" / "T7_anexo.csv", encoding="utf-8")))

    def count(sel):
        c = Counter(r["categoria_original"] for r in rows if sel(r))
        return (sum(c.values()),) + tuple(c.get(k, 0) for k in CATS)
    got = [
        count(lambda r: r["familia"] == "ci" and r["j"] == "df"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "d"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "f"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "f" and r["pais"] == "PER"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "f" and r["pais"] == "COL"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "f" and r["pais"] == "MEX"),
        count(lambda r: r["familia"] == "c"),
        count(lambda r: r["familia"] == "g"),
        count(lambda r: True),
    ]
    t6_ok = all(tuple(a[2:]) == g for a, g in zip(ARTICLE_T6, got))
    L = ["# Table 6 — classification of the 1,728 confrontation claims (regenerated by FAM13)", "",
         "FAM13 regenerated the claim-level table from stored certified values; accepted: **%s**." % ("yes" if accepted else "NO"), "",
         "| Claim family | Availability case | Claims | Sign change certified | Inconclusive within tolerance | Robustly infeasible | = article |",
         "|---|---|---|---|---|---|---|"]
    for a, g in zip(ARTICLE_T6, got):
        L.append("| %s | %s | %d | %d | %d | %d | %s |" % (a[0], a[1], *g, "yes" if tuple(a[2:]) == g else "NO"))
    (OUT / "table6.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    g = defaultdict(list)
    for r in rows:
        if r["familia"] == "ci":
            g[(r["j"], r["diseno"])].append(r)
    T = ["# Table 4 — capture ceilings at the witnesses (from the stored values regenerated by FAM13)", "",
         "| Menu | Design | Favorable witness | Unfavorable witness | Claims | accepted fav./unfav. | = article |", "|---|---|---|---|---|---|---|"]
    t4_ok, nfav, ninf = True, 0, 0
    for (j, D), (fav_a, unf_a) in ARTICLE_T4.items():
        rs = g[(j, D)]
        sup = [num(r["sup_C2"]) for r in rs if num(r["sup_C2"]) is not None]
        inf = [num(r["inf_C2"]) for r in rs if num(r["inf_C2"]) is not None]
        nfav, ninf = nfav + len(sup), ninf + len(inf)
        fav = "%.4f" % max(sup)
        lo, hi = min(inf), max(inf)
        unf = ("%.5f" % lo) if ("%.5f" % lo) == ("%.5f" % hi) else "%.4f-%.4f" % (lo, hi)
        ok = (fav, unf) == (fav_a, unf_a) and len(set(sup)) == 1 and len(rs) == 160
        t4_ok &= ok
        T.append("| %s | %s | %s | %s | %d | %d/%d | %s |" % (j, D, fav, unf, len(rs), len(sup), len(inf), "yes" if ok else "NO"))
    t4_ok &= (nfav, ninf) == (958, 956)
    T += ["", "Accepted ceiling values at %d favorable and %d unfavorable witnesses of the 960 country-instrument claims "
          "(article: 958 and 956). The favorable value is constant within each row." % (nfav, ninf)]
    (OUT / "table4_stored.md").write_text("\n".join(T) + "\n", encoding="utf-8")
    print("\n".join(L))
    print()
    print("\n".join(T))
    ok = accepted and t6_ok and t4_ok
    print()
    print("FAM13 products accepted: %s; Table 6 equals the article: %s; Table 4 (stored) equals the article: %s" % (accepted, t6_ok, t4_ok))
    print("TABLES 6 AND 4 REPRODUCED" if ok else "SOME CHECKS FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
