"""Table 4 (classification of the 1,728 claims) and Table 3 (ceilings at the witnesses) from the output of
`reproducir.py fam13-reproducir`.

FAM13 regenerates the claim-level confrontation table (T7_anexo) and its aggregate (T7) from the stored certified values
of the full run and checks that the regenerated bytes equal the accepted ones. For each claim, this script verifies the archived gap bounds under linear and statutory incidence.

Usage: python -B -I tools/tables_from_fam13.py <fam13 output folder>
Writes table6.md, table4_claims.csv and table4_stored.md next to the FAM13 folder.
"""
import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from table4_certificates import verify_claims

sys.stdout.reconfigure(encoding="utf-8")
F13 = Path(sys.argv[1]).resolve()
OUT = F13.parent
# Oxford Table 4: counts by family and withholding-only country subrows.
ARTICLE_TABLE4 = [
    ("Country-instrument, j=df", "withholding available", 320, 320, 0),
    ("Country-instrument, j=d", "domestic unchanged", 320, 320, 0),
    ("Country-instrument, j=f", "withholding available", 320, 304, 16),
    ("  Peru", "", 160, 160, 0),
    ("  Colombia", "", 96, 96, 0),
    ("  Mexico", "", 64, 48, 16),
    ("Country, best menu", "full / none", 640, 640, 0),
    ("Three countries", "full / none", 128, 128, 0),
    ("Total", "", 1728, 1712, 16),
]
ARTICLE_T4 = {("df", "G"): ("0.7917", "0.0005-0.0019"), ("df", "N"): ("0.5628", "0.0005-0.0022"),
              ("d", "G"): ("0.5475", "0.0004-0.0017"), ("d", "N"): ("0.4380", "0.0004-0.0017"),
              ("f", "G"): ("0.2737", "0.00003"), ("f", "N"): ("0.2737", "0.00003")}


def num(x):
    return None if x in ("", "null", None) else float(x)


def main():
    summary = json.loads((F13 / "resumen.json").read_text(encoding="utf-8"))
    comp = json.loads((F13 / "t7.comparacion.json").read_text(encoding="utf-8"))
    accepted = summary.get("cumple") is True and comp.get("cumple") is True and comp["estado"]["reproduccion"] == "aceptada"
    if not accepted:
        raise ValueError("FAM13 did not accept the regenerated claim table")
    with (F13 / "t7" / "ensamblajes" / "T7_anexo.csv").open(encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream))
    evidence = verify_claims(rows)

    verdicts = {r["claim"]: r["classification_both_rules"] for r in evidence}

    def count(sel):
        counts = Counter(verdicts[r["afirmacion"]] for r in rows if sel(r))
        return sum(counts.values()), counts["inconclusive"], counts["robustly infeasible"]

    got = [
        count(lambda r: r["familia"] == "ci" and r["j"] == "df"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "d"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "f"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "f" and r["pais"] == "PER"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "f" and r["pais"] == "COL"),
        count(lambda r: r["familia"] == "ci" and r["j"] == "f" and r["pais"] == "MEX"),
        count(lambda r: r["familia"] == "c"),
        count(lambda r: r["familia"] == "g"),
        count(lambda r: True),
    ]
    t6_ok = all(tuple(a[2:]) == g for a, g in zip(ARTICLE_TABLE4, got))
    L = ["# Table 4 — Classification of the 1,728 confrontation claims", "",
         "The classifications hold under both the linear allocation (E11) and statutory incidence.", "",
         "| Claim family | Availability case | Claims | Inconclusive (sign change) | Robustly infeasible |",
         "|---|---|---:|---:|---:|"]
    for (family, availability, *_), (claims, inconclusive, shortfalls) in zip(ARTICLE_TABLE4, got):
        L.append(f"| {family} | {availability} | {claims:,} | {inconclusive:,} | {shortfalls:,} |")
    L += ["", "The country subrows break down withholding alone (j=f). The [claim-level CSV](table4_claims.csv) reports the gap between fiscal capacity and the requirement, "
          "in shares of potential gains. For an inconclusive claim, the favourable lower bound exceeds +0.01 "
          "under each rule and the unfavourable upper bound is below -0.01 under both. For the Mexican "
          "shortfalls, the last column gives the upper bound over the full support.", ""]
    (OUT / "table6.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    g = defaultdict(list)
    for r in rows:
        if r["familia"] == "ci":
            g[(r["j"], r["diseno"])].append(r)
    T = ["# Table 3 — capture ceilings at the favorable and unfavorable points (stored values)", "",
         "| Menu | Design | Favorable witness | Unfavorable witness | Claims | Available witnesses, fav./unfav. |", "|---|---|---|---|---|---|"]
    t4_ok, nfav, ninf = True, 0, 0
    for (j, D), (fav_a, unf_a) in ARTICLE_T4.items():
        rs = g[(j, D)]
        sup = [num(r["sup_C2"]) for r in rs if num(r["sup_C2"]) is not None]
        inf = [num(r["inf_C2"]) for r in rs if num(r["inf_C2"]) is not None]
        nfav, ninf = nfav + len(sup), ninf + len(inf)
        fav = "%.4f" % max(sup)
        lo, hi = min(inf), max(inf)
        unf = ("%.5f" % lo) if ("%.5f" % lo) == ("%.5f" % hi) else "%.4f-%.4f" % (lo, hi)
        ok = (fav, unf) == (fav_a, unf_a) and len(set(sup)) == 1 and len(rs) == 160
        t4_ok &= ok
        T.append("| %s | %s | %s | %s | %d | %d/%d |" % (j, D, fav, unf, len(rs), len(sup), len(inf)))
    t4_ok &= (nfav, ninf) == (958, 956)
    T += ["", "Ceilings are available for %d favorable and %d unfavorable witnesses across 960 country–instrument claims. "
          "The favorable value is constant within each row." % (nfav, ninf)]
    (OUT / "table4_stored.md").write_text("\n".join(T) + "\n", encoding="utf-8")
    print("\n".join(L))
    print()
    print("\n".join(T))
    ok = accepted and t6_ok and t4_ok
    print()
    print("FAM13 products accepted: %s; Table 4 equals the article: %s; Table 3 (stored) equals the article: %s" % (accepted, t6_ok, t4_ok))
    if ok:
        with (OUT / "table4_claims.csv").open("w", newline="", encoding="utf-8") as stream:
            writer = csv.DictWriter(stream, fieldnames=evidence[0])
            writer.writeheader()
            writer.writerows(evidence)
        print(f"TABLE 4 VERIFIED: {len(evidence):,} claims under both incidence rules")
    print("TABLES 4 AND 3 REPRODUCED" if ok else "SOME CHECKS FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
